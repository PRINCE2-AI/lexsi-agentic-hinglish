"""Hash every published number so a reader can check it instead of trusting it.

    python scripts/manifest.py           # rewrite docs/MANIFEST.md from the Hub
    python scripts/manifest.py --check   # recompute and fail if anything moved

The hashes are computed from the files actually served by `primce/lexsi-runs` and
`primce/tiny-aya-hinglish-lora` at a pinned revision, not from a local copy, and the pinned
dataset files are checked against the `.sha256` files the training runs used.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

from huggingface_hub import HfApi, hf_hub_download

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "MANIFEST.md"
DATASET = "primce/lexsi-runs"
MODEL = "primce/tiny-aya-hinglish-lora"
WEIGHTS = ("sft4_adapter/adapter_model.safetensors", "sft4_adapter/adapter_config.json")
LINE = re.compile(r"^([0-9a-f]{64})  (\S+)$")


def sha256(path: str | Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def collect() -> tuple[list[tuple[str, str]], dict[str, str]]:
    api = HfApi()
    entries: list[tuple[str, str]] = []
    revisions: dict[str, str] = {}

    run_rev = api.repo_info(DATASET, repo_type="dataset").sha
    revisions[DATASET] = run_rev
    summaries = sorted(
        name
        for name in api.list_repo_files(DATASET, repo_type="dataset", revision=run_rev)
        if name.endswith("summary.json")
    )
    for name in summaries:
        local = hf_hub_download(DATASET, name, repo_type="dataset", revision=run_rev)
        entries.append((name, sha256(local)))

    model_rev = api.repo_info(MODEL, repo_type="model").sha
    revisions[MODEL] = model_rev
    for name in WEIGHTS:
        local = hf_hub_download(MODEL, name, repo_type="model", revision=model_rev)
        entries.append((name, sha256(local)))

    for sha_file in sorted((ROOT / "data").glob("*.sha256")):
        task_file = ROOT / "data" / sha_file.read_text(encoding="utf-8").split()[1]
        expected = sha_file.read_text(encoding="utf-8").split()[0]
        actual = sha256(task_file)
        if actual != expected:
            raise SystemExit(f"{task_file.name} does not match {sha_file.name}: {actual} != {expected}")
        entries.append((f"data/{task_file.name}", actual))

    return entries, revisions


def freeze_digest(entries: list[tuple[str, str]]) -> str:
    body = "\n".join(f"{digest}  {path}" for path, digest in sorted(entries))
    return hashlib.sha256(body.encode()).hexdigest()


def render(entries: list[tuple[str, str]], revisions: dict[str, str]) -> str:
    summaries = [(p, d) for p, d in entries if p.endswith("summary.json")]
    weights = [(p, d) for p, d in entries if p in WEIGHTS]
    pins = [(p, d) for p, d in entries if p.startswith("data/")]
    sections = [
        ("Published run summaries", DATASET, summaries),
        ("Shipped adapter", MODEL, weights),
        ("Pinned eval files (checked against `data/*.sha256`)", "this repo", pins),
    ]
    parts = [
        "# Manifest — sha256 of every published number",
        "",
        "Generated by `scripts/manifest.py` from the Hub, not from a local copy. Every figure in",
        "[RESULTS.md](RESULTS.md), [SAFETY.md](SAFETY.md), [GUARD.md](GUARD.md) and [STATS.md](STATS.md)",
        "names the run directory whose `summary.json` appears below, so a reader can hash the file",
        "before using the number.",
        "",
        f"**Freeze digest: `{freeze_digest(entries)}`** — sha256 over every line below, sorted.",
        "",
        "Repositories pinned at generation time:",
        "",
    ]
    for repo, rev in revisions.items():
        parts.append(f"- `{repo}` @ `{rev}`")
    parts.append("")
    for title, source, rows in sections:
        parts.append(f"## {title} — {source} ({len(rows)} files)")
        parts.append("")
        parts.append("```")
        parts.extend(f"{digest}  {path}" for path, digest in rows)
        parts.append("```")
        parts.append("")
    parts.extend(
        [
            "## How to check",
            "",
            "```console",
            "$ python scripts/manifest.py --check",
            f"all {len(entries)} hashes match docs/MANIFEST.md",
            "```",
            "",
            "A mismatch means either a published file changed after this manifest was written or the",
            "manifest is stale; regenerate it and commit the diff with the reason.",
            "",
        ]
    )
    return "\n".join(parts)


def parse(text: str) -> dict[str, str]:
    found: dict[str, str] = {}
    for line in text.splitlines():
        match = LINE.match(line.strip())
        if match:
            found[match.group(2)] = match.group(1)
    return found


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    entries, revisions = collect()
    if args.check:
        if not OUT.exists():
            raise SystemExit("docs/MANIFEST.md is missing; run without --check")
        recorded = parse(OUT.read_text(encoding="utf-8"))
        current = dict(entries)
        missing = sorted(set(recorded) - set(current))
        stale = sorted(path for path in recorded if path in current and recorded[path] != current[path])
        if missing or stale:
            for path in missing:
                print(f"gone: {path}")
            for path in stale:
                print(f"changed: {path}")
            raise SystemExit(f"{len(missing)} missing, {len(stale)} changed")
        print(f"all {len(current)} hashes match docs/MANIFEST.md")
        return

    OUT.write_text(render(entries, revisions), encoding="utf-8")
    print(f"wrote {OUT} ({len(entries)} files, freeze {freeze_digest(entries)[:12]})")


if __name__ == "__main__":
    main()
